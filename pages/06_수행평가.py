    games = mbti_games[user_mbti]
    displayed_count = 0
    
    for idx, game in enumerate(games):
        # 필터링 조건 체크
        if filter_mode == "솔로 플레이 포함" and "솔로" not in game['mode']:
            continue
        elif filter_mode == "멀티 전용/권장만" and ("멀티 전용" not in game['mode'] and "멀티 권장" not in game['mode']):
            continue
            
        displayed_count += 1
        st.markdown(f"### {displayed_count}. {game['name']}")
        st.markdown(f"**👥 플레이 방식:** `{game['mode']}`")
        st.info(f"**🧐 추천 이유**\n\n{game['style']}")
        st.write("") 
        
    if displayed_count == 0:
        st.warning("선택한 필터 조건에 맞는 게임이 없습니다. 다른 필터를 선택해 주세요!")

